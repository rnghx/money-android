const assert=require('node:assert/strict'),M=require('../app/src/main/assets/core.js');
assert.equal(M.decimalMinor('2530.765'),253077);
assert.equal(M.decimalMinor('-0.005'),-1);
assert.equal(M.decimalMinor('0'),0);
assert.equal(M.decimalMinor('NaN'),null);
assert.equal(M.decimalMinor('1e6'),null);
assert.equal(M.decimalMinor('900719925474099100'),null);
assert.equal(M.convertMinor(900000,'RUB','USD','90'),10000);
assert.equal(M.convertMinor(10000,'USD','RUB','90'),900000);
assert.equal(M.convertMinor(10000,'USD','USD',null),10000);
assert.equal(M.convertMinor(10000,'USD','RUB',null),null);
assert.equal(M.convertMinor(10000,'USD','RUB','0'),null);
assert.equal(M.convertMinor(10000,'USD','RUB','-90'),null);
assert.equal(M.convertMinor(Number.MAX_SAFE_INTEGER,'USD','RUB','100'),null);
assert.equal(M.convertDecimalMinor('1.005','USD','USD',null),101);
assert.equal(M.convertDecimalMinor('-1.005','USD','USD',null),-101);
assert.equal(M.convertDecimalMinor('2530.765','USD','RUB','90.1234'),22808115);
assert.equal(M.convertDecimalMinor('9000','RUB','USD','90'),10000);
assert.equal(M.convertDecimalMinor('1','USD','RUB',null),null);
assert.equal(M.convertDecimalMinor('NaN','USD','RUB','90'),null);
console.log('Asset conversion checks passed: decimal rounding, RUB/USD, no invented rates or unsafe totals.');
