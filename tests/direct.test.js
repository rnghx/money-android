const assert=require('node:assert/strict');
const M=require('../app/src/main/assets/core.js');
const op=(id,amount,more={})=>({uohId:id,date:'09.11.2026T12:34:56',isFinancial:true,state:{category:'executed',name:'FINANCIAL'},form:'ExtCardPayment',operationAmount:{amount,currencyCode:'RUB'},description:'Магазин',...more});
const input=[op('expense',-123.45),op('income',300),op('self',-1000,{form:'UfsTransferSelf',commission:{amount:2.50,currencyCode:'RUB'}}),op('cancel',-100,{state:{category:'cancel',name:'UNAUTHORIZATION'}}),op('pending',-10,{state:{category:'executed',name:'AUTHORIZATION'}})];
const rows=M.bankRows(input);
assert.equal(rows.length,5);
assert.deepEqual(M.totals(rows),{income:30000,expense:13595,net:16405});
assert.equal(rows.find(r=>r.id==='bank:self').type,'transfer');
assert.equal(rows.find(r=>r.id==='bank:self:fee').amount,250);
assert.equal(rows.find(r=>r.id==='bank:pending').hold,true);
assert.equal(M.bankRows([op('owned',-100,{ownTransfer:true})])[0].type,'transfer');
assert.equal(M.bankRows([op('fx',-5,{operationAmount:{amount:-5,currencyCode:'USD'},nationalAmount:{amount:-450,currencyCode:'RUB'}})])[0].amount,45000);
assert.throws(()=>M.bankRows([op('fx',-5,{operationAmount:{amount:-5,currencyCode:'USD'}})]));
assert.throws(()=>M.bankRows([op('repeat',1),op('repeat',2)]));
assert.throws(()=>M.bankRows([op('unknown',1,{state:{name:'NEW',category:'executed'}})]));
assert.throws(()=>M.bankRows([op('date',1,{date:'31.02.2026T12:00:00'})]));
const previous=[{...rows[0],userType:'transfer',type:'transfer'}, {...rows[1],date:'2026-10-01'}, {...rows[2],id:'bank:removed'}, {id:'statement',source:'statement',date:'2026-11-01'}];
const merged=M.mergeBank(previous,[{...rows[0],amount:20000}],'2026-11');
assert.equal(merged.find(r=>r.id===rows[0].id).amount,20000);
assert.equal(merged.find(r=>r.id===rows[0].id).type,'transfer');
assert.equal(merged.some(r=>r.id==='bank:removed'),false);
assert.equal(merged.some(r=>r.id==='statement'),true);
assert.equal(merged.some(r=>r.date==='2026-10-01'),true);
assert.deepEqual(M.mergeBank(merged,[{...rows[0],amount:20000}],'2026-11'),merged);
assert.throws(()=>M.mergeBank(previous,rows,'2026-10'));
console.log('Direct synchronization checks passed: RUB, FX, fees, own transfers, cancellation, stable updates.');
