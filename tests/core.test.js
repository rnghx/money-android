const assert=require('node:assert/strict');
const M=require('../app/src/main/assets/core.js');
assert.equal(M.amount('−1\u202f234,56 ₽'),-123456);
assert.equal(M.amount('1 234.50 RUB'),123450);
assert.equal(M.amount('12,345'),null);
assert.equal(M.amount(''),null);
assert.equal(M.date('31.02.2026'),null);
assert.equal(M.date('09.11.2026 12:03'),'2026-11-09');
const csv='Дата;Описание;Сумма;Тип\r\n09.11.2026;"Магазин; продукты";"-1 234,56";Расход\r\n09.11.2026;"Возврат ""товара""";500;Доход';
const table=M.csv(csv),rows=M.csvRows(table.slice(1),M.mapping(table[0]));
assert.equal(rows[0].amount,123456);assert.equal(rows[0].type,'expense');assert.equal(rows[0].description,'Магазин; продукты');
assert.equal(rows[1].type,'income');assert.equal(rows[1].description,'Возврат "товара"');
assert.equal(M.csvRows([['09.11.2026','Магазин','100']],{date:0,description:1,amount:2})[0].type,'');
const split=M.csvRows([['09.11.2026','Оплата','150,50','']],{date:0,description:1,amount:-1,expense:2,income:3});
assert.equal(split[0].amount,15050);assert.equal(split[0].type,'expense');
const bad=M.csvRows([['09.11.2026','Оплата','150','200']],{date:0,description:1,amount:-1,expense:2,income:3});assert.equal(M.valid(bad[0]),false);
assert.equal(M.pdfRows('09.11.2026\nПокупка −100,00 ₽')[0].type,'expense');
assert.equal(M.pdfRows('09.11.2026\nПокупка 100,00 ₽ Баланс 200,00 ₽')[0].amount,null);
assert.deepEqual(M.totals([{type:'income',amount:10000},{type:'expense',amount:3000},{type:'transfer',amount:5000},{type:'expense',amount:2000,review:true}]),{income:10000,expense:3000,net:7000});
console.log('Core checks passed: money, dates, CSV, PDF ambiguity, totals.');
