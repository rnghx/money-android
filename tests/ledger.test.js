const assert=require('node:assert/strict'),L=require('../app/src/main/assets/ledger.js'),M=require('../app/src/main/assets/core.js');
const row={id:'bank:one',date:'2026-11-02',description:'STORE',amount:50000,type:'expense',category:'Продукты',source:'bank',review:false};
const state=L.init({transactions:[row],syncedMonths:['2026-10','2026-11']});
state.operationEdits[row.id]={description:'На неделю',categoryId:'services',type:'expense',amount:70000,date:'2026-11-03'};
state.transactions=M.mergeBank(state.transactions,[{...row,description:'UPDATED BANK TITLE',amount:60000}],'2026-11');
assert.equal(L.rows(state)[0].description,'На неделю');assert.equal(L.rows(state)[0].amount,70000);
assert.equal(state.transactions[0].amount,60000,'Keep bank facts intact for reset');
const services=state.categories.find(c=>c.id==='services');services.name='Онлайн';
assert.equal(L.groups(state,L.rows(state),'expense')[0].name,'Онлайн');
state.transactions.push({...row,id:'bank:two',category:'Подписки'});
assert.equal(L.rows(state)[1].categoryId,'services','Renaming must keep future bank assignments');
delete state.operationEdits[row.id];assert.equal(L.rows(state)[0].description,'UPDATED BANK TITLE');
assert.equal(L.monthly(state,'2026-11','expense')[0].amount,null,'Unknown history is not zero');
assert.equal(L.comparison(state,'2026-09','expense','2026-11-09'),null);
state.transactions=[{...row,date:'2026-11-02',amount:50000},{...row,id:'b',date:'2026-10-02',amount:100000},{...row,id:'c',date:'2026-10-28',amount:400000}];
assert.equal(L.comparison(state,'2026-11','expense','2026-11-09').delta,-.5,'Compare elapsed days, not partial month to entire prior month');
assert.equal(L.comparison(state,'2026-11','expense','2026-12-01').delta,-.9,'Past months compare full months');
const goal={targetMinor:100000,currency:'RUB'};
assert.equal(L.progress(goal,{complete:true,amount:50000}),.5);
assert.equal(L.progress(goal,{complete:false,amount:50000}),null);
assert.equal(L.progress(goal,{complete:true,amount:null}),null);
assert.equal(L.progress(goal,{complete:true,amount:-50000}),0);
assert.equal(L.progress(goal,{complete:true,amount:150000}),1);
console.log('Ledger checks passed: persistent edits, category rename, fair comparison, missing months and goal progress.');
